# build_shipped_manifest.py
import hashlib
import os
from pathlib import Path

# --- Adjust these two lines to match your actual layout ---
SHIPPED_DIR = Path.home() / "CogniSuite" / "TaxTemplates" / "shipped"
OUTPUT_PATH = Path(__file__).parent / "shipped_manifest.py"
# ----------------------------------------------------------

def compute_sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        h.update(f.read())
    return h.hexdigest()

def main():
    if not SHIPPED_DIR.exists():
        print(f"Shipped templates directory not found: {SHIPPED_DIR}")
        print("Create it and add your .json templates before running this script.")
        return

    entries = {}
    for fname in sorted(os.listdir(SHIPPED_DIR)):
        if not fname.endswith(".json"):
            continue
        template_id = fname[:-5]
        entries[template_id] = compute_sha256(SHIPPED_DIR / fname)

    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write('"""\n')
        f.write("Auto-generated by build_shipped_manifest.py.\n")
        f.write("Do not edit by hand -- rerun the build script instead.\n")
        f.write('"""\n\n')
        f.write("SHIPPED_TEMPLATE_MANIFEST = {\n")
        for tid, digest in entries.items():
            f.write(f'    "{tid}": "{digest}",\n')
        f.write("}\n")

    print(f"Wrote {len(entries)} entries to {OUTPUT_PATH}")

if __name__ == "__main__":
    main()
